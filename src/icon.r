/*
   Quill's application icon: a bold "Q" letterform (ring + diagonal tail),
   using 4 colors from the standard classic Mac OS 16-color icon palette -
   white (index 0, background), black (15, outline), brown (10, ring fill),
   blue (6, tail). Generated programmatically (see the repo's scratchpad
   gen_icon.py at generation time) rather than hand-plotted, since hand
   transcribing ~1KB of pixel data is exactly the kind of thing that's easy
   to get subtly wrong.

   BNDL/FREF wire this up as the Finder icon for the app itself: BNDL's
   signature ('Quil') must match the creator code CMakeLists.txt passes to
   add_application(), or Finder won't associate this icon family with the
   app. icl4/ics4 (color) and ICN#/ics# (1-bit fallback) all share resource
   ID 128 - Finder finds the color variants automatically once BNDL points
   it at the ICN#/FREF pair.
*/

