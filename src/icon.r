/*
   Quill's application icon: a stylized quill pen - a diagonal tapered
   shaft, feather barbs branching off one edge, and a small ink drop at the
   nib - using 4 colors from the standard classic Mac OS 16-color icon
   palette: white (index 0, background), black (15, outline/barbs/nib),
   tan (11, feather fill), blue (6, ink drop).

   Generated programmatically (circle/line-segment distance math over a
   32x32 and 16x16 grid), not hand-plotted - accurately hand-transcribing
   ~1KB of hex bitmap data across four resources is exactly the kind of
   tedious, error-prone task a script does more reliably. The 16-color
   palette's index order was cross-checked against two independent sources
   rather than trusted from memory, since getting an index wrong would
   silently produce a wrong-but-plausible-looking color.

   BNDL/FREF wire this up as the Finder icon for the app itself: BNDL's
   signature ('Quil') must match the creator code CMakeLists.txt passes to
   add_application(), or Finder won't associate this icon family with the
   app. icl4/ics4 (color) and ICN#/ics# (1-bit fallback) all share resource
   ID 128 - Finder finds the color variants automatically once BNDL points
   it at the ICN#/FREF pair.
*/

